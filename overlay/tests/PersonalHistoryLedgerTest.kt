package com.nuvio.app.features.player

fun main() {
    var assertions = 0
    fun verify(ok: Boolean) { check(ok) { "Assertion ${assertions + 1} failed" }; assertions++ }
    val h = PersonalHistoryLedger(null)
    verify(h.get("tt123") == null)
    verify(h.record("tt123", 1000, true, 1))
    verify(h.get("tt123") == HistoryEntry(1000, 1, 1))
    verify(h.record("tt123", 2000, false, 2))
    verify(h.get("tt123") == HistoryEntry(3000, 1, 2))
    verify(h.record("tt123", 3000, true, 3))
    verify(h.get("tt123") == HistoryEntry(6000, 2, 3))
    verify(h.record("tt123:1:2", 10, true, 4))
    verify(h.get("tt123:1:2") == HistoryEntry(10, 1, 4))
    verify(!h.record("https://private.example/token", 5, true, 5))
    verify(!h.record("", 5, true, 5))
    verify(!h.record("tt123", 0, true, 5))
    verify(!h.record("tt123", -1, true, 5))
    verify(!h.record("tt123", 10, true, -1))
    verify(!h.record("x".repeat(257), 1, true, 1))
    verify(h.record("é|\n", 10, true, 4))
    val encoded = h.encode()
    val restored = PersonalHistoryLedger(encoded)
    verify(restored.get("tt123") == h.get("tt123"))
    verify(restored.get("é|\n") == h.get("é|\n"))
    verify(restored.encode() == encoded)
    verify(PersonalHistoryLedger("v2\n6162|1|1|1").get("ab") == null)
    verify(PersonalHistoryLedger("v1\n6162|-1|1|1").get("ab") == null)
    verify(PersonalHistoryLedger("v1\n6162|1|0|1").get("ab") == null)
    verify(PersonalHistoryLedger("v1\n6162|1|1|-1").get("ab") == null)
    verify(PersonalHistoryLedger("v1\n6162|1|1|1\nbad\n").get("ab") == HistoryEntry(1,1,1))
    val bounded = PersonalHistoryLedger(null)
    for (i in 1..105) bounded.record("id$i", 10, true, i.toLong())
    verify(bounded.get("id1") == null)
    verify(bounded.get("id5") == null)
    verify(bounded.get("id6") != null)
    verify(bounded.get("id105") != null)
    verify(bounded.encode().lines().size == 101)
    val t = PersonalSleepTimer()
    verify(t.remainingMs(0) == null)
    verify(!t.consumeIfDue(0))
    t.set(15, 100)
    verify(t.remainingMs(100) == 900000L)
    verify(t.remainingMs(900099) == 1L)
    verify(!t.consumeIfDue(900099))
    verify(t.consumeIfDue(900100))
    verify(!t.consumeIfDue(900101))
    t.set(30, 0)
    verify(t.remainingMs(0) == 1800000L)
    t.set(60, 1000)
    verify(t.remainingMs(1000) == 3600000L)
    t.set(0, 2000)
    verify(t.remainingMs(3000) == null)
    t.set(10, 0)
    verify(t.remainingMs(0) == null)
    t.set(15, Long.MAX_VALUE)
    verify(t.remainingMs(Long.MAX_VALUE) == null)
    println("PASS: $assertions history and sleep timer assertions")
}
