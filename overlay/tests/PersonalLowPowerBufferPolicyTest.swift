private var policy = PersonalLowPowerBufferPolicy()
var checks = 0
func verify(_ condition: @autoclosure () -> Bool) { precondition(condition(), "Failed check \(checks + 1)"); checks += 1 }
func observe(_ now: Double, _ eligible: Bool = true, _ ahead: Double = 40) -> Double { policy.observe(now: now, eligible: eligible, ahead: ahead) }
verify(observe(0) == 0)
verify(observe(59) == 0)
verify(observe(60) == 15)
verify(policy.active)
verify(observe(61, true, 15) == 15)
verify(observe(62, true, 10) == 15)
verify(observe(63, true, 9.99) == 0)
verify(!policy.active)
verify(observe(64) == 0)
verify(observe(124) == 15)
verify(observe(125, false) == 0)
verify(observe(126) == 0)
verify(observe(186) == 15)
verify(observe(185) == 0)
verify(observe(245) == 15)
verify(observe(.nan) == 0)
verify(observe(300, true, .infinity) == 0)
verify(observe(301, true, -1) == 0)
verify(observe(302, true, 29) == 0)
verify(observe(362, true, 30) == 0)
verify(observe(422, true, 30) == 15)
verify(observe(423, false) == 0)
print("PASS: \(checks) low-power buffer assertions")
