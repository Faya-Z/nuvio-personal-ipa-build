package com.nuvio.app.features.player
fun main() {
    val g = StallRecoveryGate()
    check(!g.observe(true, true, 1000, 0))
    check(!g.observe(true, true, 1000, 14999))
    check(g.observe(true, true, 1000, 15000))
    check(!g.observe(true, true, 1000, 30000))
    check(!g.observe(true, false, 1000, 31000))
    check(!g.observe(true, true, 1000, 32000))
    check(!g.observe(true, true, 2000, 47000))
    check(!g.observe(true, true, 2000, 61999))
    check(g.observe(true, true, 2000, 62000))
    check(!g.observe(false, true, 2000, 63000))
    check(!g.observe(true, true, 2000, 64000))
    check(!g.observe(true, true, 2000, 63999))
    check(!g.observe(true, true, 2000, 78998))
    check(g.observe(true, true, 2000, 78999))
    g.reset()
    check(!g.observe(true, true, 2000, 90000))
    val s = SourceReliability(2)
    check(s.score("unknown") == 0.5)
    check(s.best(listOf("a", "b")) { it } == "a")
    check(s.best(emptyList<String>()) { it } == null)
    s.record("a", false)
    check(s.score("a") == 0.4)
    check(s.best(listOf("a", "b")) { it } == "b")
    s.record("b", true)
    check(s.score("b") == 0.6)
    s.record(null, false)
    check(s.score(null) == 0.5)
    s.record("c", true)
    check(s.score("a") == 0.5)
    repeat(1000) { s.record("b", false) }
    check(s.score("b") in 0.0..0.5)
    repeat(1000) { s.record("b", true) }
    check(s.score("b") in 0.5..1.0)
    check(s.best(listOf("c", "b")) { it } == "b")
    println("PASS: 26 recovery policy assertions")
}
