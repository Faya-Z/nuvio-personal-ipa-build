package com.nuvio.app.features.player
fun main() {
    var count = 0
    fun expect(value: Boolean) { check(value) { "Assertion ${count+1}" }; count++ }
    data class Source(val name:String, val score:Double, val n:Int, val direct:Boolean=true)
    val a=Source("A",.3,5); val b=Source("B",.8,5); val c=Source("C",.8,5)
    fun rank(vararg s:Source) = rankInitialSources(s.toList(), {it.score},{it.n},{it.direct})
    expect(rank().isEmpty())
    expect(rank(a)==listOf(a))
    expect(rank(a,b,c)==listOf(b,a,c))
    expect(rank(b,c,a)==listOf(b,c,a))
    expect(rank(a.copy(n=2),b).first().name=="A")
    expect(rank(a,b.copy(n=2)).first()==a)
    expect(rank(a,b.copy(direct=false))==listOf(a,b.copy(direct=false)))
    expect(rank(a,b.copy(score=.4)).first()==a)
    expect(rank(a,b.copy(score=.46)).first().name=="B")
    expect(rank(a,b.copy(n=0),c).first()==c)
    listOf("en","eng","English"," EN_us ","en-GB","eng-US","en-Latn-US").forEach { expect(audioLanguageStatus(it)==EnglishAudioStatus.English) }
    listOf(null,"","und","unknown","default","mul","zxx","English subtitles","enforced","none").forEach { expect(audioLanguageStatus(it)==EnglishAudioStatus.Unknown) }
    listOf("fr","fra","ja","bn-BD","es-419").forEach { expect(audioLanguageStatus(it)==EnglishAudioStatus.Other) }
    val selected=EnglishTrackCandidate(0,"fr","French",true)
    val english=EnglishTrackCandidate(1,"eng","Main audio",false)
    val commentary=EnglishTrackCandidate(2,"en","Director's commentary",false)
    expect(preferredVerifiedEnglishTrack(emptyList())==null)
    expect(preferredVerifiedEnglishTrack(listOf(english))==null)
    expect(preferredVerifiedEnglishTrack(listOf(selected,commentary,english))==1)
    expect(preferredVerifiedEnglishTrack(listOf(selected,commentary))==null)
    expect(preferredVerifiedEnglishTrack(listOf(selected.copy(language="en"),english))==null)
    expect(preferredVerifiedEnglishTrack(listOf(selected,english.copy(language=null)))==null)
    expect(preferredVerifiedEnglishTrack(listOf(selected,english.copy(index=-1)))==null)
    expect(preferredVerifiedEnglishTrack(listOf(selected.copy(language=null),english))==1)
    val h=PlaybackSessionHistory()
    h.observe(0,0,true,1f); h.observe(250,250,true,1f)
    expect(h.watchedMediaMs==250L)
    expect(h.sessions==1)
    h.observe(500,500,true,1f); expect(h.watchedMediaMs==500L)
    h.observe(20_000,750,true,1f); expect(h.watchedMediaMs==500L)
    h.observe(20_250,1000,true,1f); expect(h.watchedMediaMs==750L)
    h.observe(20_250,1250,false,1f); h.observe(21_000,1500,true,1f); expect(h.watchedMediaMs==750L)
    h.observe(21_500,1750,true,2f); expect(h.watchedMediaMs==1250L)
    h.observe(1_000,2000,true,1f); expect(h.watchedMediaMs==1250L)
    h.observe(2_000,5000,true,1f); expect(h.watchedMediaMs==1250L)
    h.resetContinuity(); h.observe(1_000,5250,true,1f); expect(h.watchedMediaMs==1250L)
    h.observe(1250,5500,true,Float.NaN); expect(h.watchedMediaMs==1250L)
    expect(h.lastPositionMs==1000L)
    val r=SourceReliability(nowMs={1000L})
    expect(r.observations("x")==0)
    repeat(3) {r.record("x",true)};expect(r.observations("x")==3)
    val restored=SourceReliability(persisted=r.snapshot(),nowMs={1000L})
    expect(restored.observations("x")==3)
    val stale=SourceReliability(persisted=r.snapshot(),nowMs={1000L+15L*86400000})
    expect(stale.observations("x")==0)
    println("PASS: $count personal selection/history assertions")
}
